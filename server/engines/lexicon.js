/**
 * The bundled Sanskrit dictionary for the free translation engine.
 *
 * Written as compact `key=value` pairs separated by "|" — one line per topic,
 * which keeps this file readable and makes duplicate keys impossible to miss.
 *
 * This dictionary is what makes the app work with NO API key and NO cost.
 * It covers the words that appear in everyday sentences; anything it does not
 * know is passed through unchanged rather than guessed at.
 */

/** Turns "a=१|b=२" into { a: '१', b: '२' }. */
function dict(pairs) {
  const out = {};
  for (const entry of String(pairs).split('|')) {
    const text = entry.trim();
    if (!text) continue;
    const split = text.indexOf('=');
    if (split < 1) continue;
    out[text.slice(0, split).trim()] = text.slice(split + 1).trim();
  }
  return out;
}

